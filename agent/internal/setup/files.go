// NftMarker identifies an /etc/nftables.conf that we generated. Without it in
// an existing file, setup refuses to overwrite: that file is somebody else's
// firewall until proven otherwise.
const NftMarker = "autoproxy-managed"

// baseNft is the base firewall. @SSH_PORT@, @WG_PORT@ and @API_PORT@ are
// substituted at install time.
//
// There is deliberately NO forward chain here. The agent's table
// (inet autoproxy_rules) owns the forward hook and its policy. nftables
// requires every base chain at a hook to accept, so a forward chain in both
// files would split ownership of forwarding across two writers.
const baseNft = `#!/usr/sbin/nft -f
# autoproxy-managed: generated by "autoproxy-agent setup" -- do not edit by hand.
#
# Pelican Auto Proxy base ruleset.
#
# We never "flush ruleset" here: that would also wipe the agent-owned
# inet autoproxy_rules table, closing every game port until the next sync.
# Instead we declare-then-delete only our own table by exact name, so
# re-applying this file never touches the agent's rules.

table inet autoproxy_base {}
delete table inet autoproxy_base

table inet autoproxy_base {
	chain input {
		type filter hook input priority filter; policy drop;

		iif lo accept
		ct state established,related accept
		ct state invalid drop

		ip protocol icmp accept
		ip6 nexthdr icmpv6 accept

		# SSH. Detected from sshd at install time.
		tcp dport @SSH_PORT@ accept

		# WireGuard: the clients dial in here.
		udp dport @WG_PORT@ accept

		# Agent API. Reachable from anywhere because the Pelican panel may be
		# anywhere; it is protected by TLS and a bearer token, not by address.
		tcp dport @API_PORT@ accept
	}

	chain output {
		type filter hook output priority filter; policy accept;
	}
}

# Guard: /etc/autoproxy/rules.nft must always exist. nftables aborts loading
# this ENTIRE file when an include target is absent, which would leave the box
# with no firewall at boot -- not just a missing agent table. Setup creates an
# empty placeholder so the include always resolves.
include "/etc/autoproxy/rules.nft"
`

