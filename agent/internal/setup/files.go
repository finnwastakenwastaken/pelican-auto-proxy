// WG0Conf renders /etc/wireguard/wg0.conf.
//
// There are deliberately NO hooks (PostUp/PreUp/...): wg-quick treats a
// failing hook as fatal and deletes the interface it has just created, so one
// sysctl the kernel happens to refuse -- a container, LXC, a locked-down
// provider kernel -- would take the whole tunnel down with a message nobody
// reads. The VPS does not need a loosened rp_filter anyway: every address a
// peer sends from is in its AllowedIPs and therefore routed back down wg0, so
// the strict reverse-path check passes. (The client does need rp_filter=2;
// that is its own business.)
//
// There are also no peers. They are added live by the agent from peers.json;
// two writers on this file is how peers silently disappear after a reboot.
//
// FwMark IS written here, unlike everything else dynamic, because it must be
// true from the instant wg-quick brings the interface up, not from whenever
// the agent next starts. The mark is what tells the peer-routing ip rule
// (see package wg) that a packet is the tunnel's own encrypted transport and
// must therefore consult the main table, not the peer table. If the interface
// came up unmarked and a site peer's lan_cidrs happened to cover that peer's
// own endpoint address, the VPS would route its own handshakes into the
// tunnel it is trying to open, and the tunnel would never come up. The agent
// sets the same mark again on start with "wg set" -- that is what repairs an
// existing install whose wg0.conf predates this -- but the boot path must not
// depend on the agent winning a race with wg-quick.
//
// FwMark is a plain "wg setconf" [Interface] key, not a wg-quick hook, so it
// carries none of the "a failing hook deletes the interface" risk above.
func WG0Conf(tunnelIP string, bits, listenPort int, privateKey string) string {
	return fmt.Sprintf(`# autoproxy-managed: rewritten by "autoproxy-agent setup".
# Peers are NOT listed here. They are added live by the agent from
# /var/lib/autoproxy/peers.json; do not add peers by hand.
[Interface]
Address = %s/%d
ListenPort = %d
PrivateKey = %s
# Marks this interface's own encrypted packets so the "not fwmark %s lookup %s"
# ip rule lets them reach the peer's real endpoint through the main table
# instead of looping back into the tunnel. Do not change it here alone; the
# agent uses the same constant (agent/internal/wg.DefaultFWMark).
FwMark = %s
`, tunnelIP, bits, listenPort, privateKey, wg.DefaultFWMark, wg.DefaultTable, wg.DefaultFWMark)
}

